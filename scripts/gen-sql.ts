/**
 * Emits a single bootstrap SQL file: the schema migration followed by every
 * seed row as INSERTs. Idempotent — wrapped so re-running replaces seed data
 * cleanly. Useful for the Supabase SQL Editor or `psql -f`.
 *
 *   npx tsx scripts/gen-sql.ts > seed_bootstrap.sql
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import {
  SEED_DIR,
  loadAfcd,
  loadFoods,
  loadConversions,
  loadRecipes,
} from "./seed";

const migration = readFileSync(
  join(SEED_DIR, "..", "supabase", "migrations", "0001_init.sql"),
  "utf8",
);

const q = (v: unknown): string =>
  v === null || v === undefined
    ? "NULL"
    : typeof v === "number"
      ? String(v)
      : typeof v === "boolean"
        ? v
          ? "true"
          : "false"
        : "'" + String(v).replace(/'/g, "''") + "'";

const out: string[] = [];
out.push("-- Generated by scripts/gen-sql.ts — schema + seed bootstrap.");
out.push("begin;");
out.push("");
out.push(migration.trim());
out.push("");
out.push("-- ---- Seed data --------------------------------------------------");

for (const a of loadAfcd()) {
  out.push(
    `insert into afcd_master values (${[a.public_food_key, a.food_name, a.classification, a.specific_gravity, a.energy_kcal, a.protein, a.fat, a.satfat, a.carb_avail, a.sugars, a.fibre, a.sodium_mg].map(q).join(",")}) on conflict (public_food_key) do nothing;`,
  );
}
for (const f of loadFoods()) {
  out.push(
    `insert into foods values (${[f.food_id, f.display_name, f.afcd_key, f.source, f.energy_kcal_100g, f.protein_100g, f.fat_100g, f.carb_avail_100g, f.fibre_100g, f.density_g_ml, f.verified, f.match_note].map(q).join(",")}) on conflict (food_id) do nothing;`,
  );
}
for (const c of loadConversions()) {
  out.push(
    `insert into unit_conversions (food_id,unit,grams,basis) values (${[c.food_id, c.unit, c.grams, c.basis].map(q).join(",")}) on conflict (food_id,unit) do nothing;`,
  );
}

let rid = 0;
for (const r of loadRecipes()) {
  rid++;
  const ridv = `'00000000-0000-4000-8000-${String(rid).padStart(12, "0")}'`;
  out.push(`delete from recipes where title = ${q(r.title)};`);
  out.push(
    `insert into recipes (id,title,servings,time_minutes) values (${ridv},${q(r.title)},${r.servings},${r.time_minutes});`,
  );
  r.ingredients.forEach((i, idx) => {
    out.push(
      `insert into ingredient_lines (recipe_id,food_id,section,position,quantity,unit,prep_note) values (${ridv},${q(i.food_id)},${q(i.section ?? null)},${idx},${i.quantity},${q(i.unit)},${q(i.prep && i.prep.trim() ? i.prep : null)});`,
    );
  });
}

out.push("");
out.push("commit;");
process.stdout.write(out.join("\n") + "\n");
