"""Write tests/sql/ausnut_apply.test.sql from REAL changeset rows (a sample covering every op and batch).
Run build_changeset.py first. The test needs 0041–0043 applied (or prepended in the same transaction) and
rolls everything back at the end. Usage: python3 -I scripts/ausnut/make_apply_test.py"""
import csv, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(HERE))
CS = os.path.join(REPO, "seed", "ausnut2023", "changeset")
FOODS = {"g3a": {"almond", "milk_chocolate", "honey", "vanilla_extract", "lemon"},
         "g3b": {"pancake", "danish_feta", "paprika", "soy_sauce", "protein_powder", "soba_noodles", "pepita", "haloumi"},
         "g3c": {"dijon_mustard", "sundried_tomato", "garlic", "pear", "celery", "green_bean", "self_raising_flour", "iceberg_lettuce", "pepper"},
         "g3d": {"fish_sauce", "chicken_breast"},
         "g4a": {"squash_button", "gelatine_powder", "olive_oil_spray", "blackberries"},
         "g4b": {"tin_tuna_in_spring_water", "soy", "aaa", "salt_and_pepper", "each_paprika_and_cumin", "each_onion_and_garlic_powder"}}
rows, keys = [], set()
for b in ["g3a", "g3b", "g3c", "g3d", "g4a", "g4b", "g4c"]:
    for l in open(os.path.join(CS, f"{b}.jsonl")):
        r = json.loads(l)
        if b == "g4c":
            keep = r["op"] != "set_recipe_issue" or "FLOUR" in (r["args"].get("data_issue") or "")
        else:
            keep = r["food_id"] in FOODS[b]
        if keep:
            if "--compact" in sys.argv:          # same ops, shorter text (for pasting into a one-shot dry run)
                a_ = r["args"]
                if "suggestion" in a_: a_["suggestion"] = {"note": "trimmed for the dry run"}
                for k_ in ("evidence", "reason"):
                    if k_ in a_: a_[k_] = a_[k_][:60]
                for d_ in (a_.get("set") or {}, a_.get("row") or {}):
                    for k_ in ("ai_evidence", "match_note"):
                        if d_.get(k_): d_[k_] = d_[k_][:60]
                r["note"] = (r["note"] or "")[:50] or None
            rows.append(r)
            a = r["args"]
            for k in (a.get("ausnut_key"), (a.get("set") or {}).get("ausnut_key"), (a.get("row") or {}).get("ausnut_key")):
                if k: keys.add(k)
master = {m["public_food_key"]: m["food_name"] for m in csv.DictReader(open(os.path.join(REPO, "seed/ausnut2023/reference/ausnut_master.csv"), encoding="utf-8-sig"))}
q = lambda s: "null" if s is None else "'" + str(s).replace("'", "''") + "'"
seq = {}
vals = []
for r in rows:
    seq[r["batch"]] = seq.get(r["batch"], 0) + 1
    vals.append(f"({q(r['batch'])}, {seq[r['batch']]}, {q(r['op'])}, {q(r['food_id'])}, {q(json.dumps(r['args'], ensure_ascii=False))}::jsonb, {q(r['note'])})")
sql = f"""-- tests/sql/ausnut_apply.test.sql — GENERATED by scripts/ausnut/make_apply_test.py from the real changeset.
-- {len(rows)} real ops covering every op type and batch. Needs 0041–0043; everything rolls back.
insert into ausnut_master (public_food_key, survey_id, food_name) values
{",".join(chr(10) + f"  ({q(k)}, {q('T' + k)}, {q(master[k])})" for k in sorted(keys))}
on conflict do nothing;
insert into ausnut_changeset (batch, seq, op, food_id, args, note) values
{("," + chr(10)).join("  " + v for v in vals)};
""" + open(os.path.join(HERE, "apply_test_asserts.sql")).read()
out = os.path.join(REPO, "tests/sql/ausnut_apply.test.sql") if "--compact" not in sys.argv else sys.argv[-1]
open(out, "w").write(sql)
print(f"{len(rows)} ops, {len(keys)} AUSNUT keys → {out}")
